package app.naviamp.storage

import kotlinx.serialization.Serializable

/** Connection configuration only. Cache sync/scan/version markers deliberately do not survive a purge. */
@Serializable
internal data class StorageRecoveryConnection(
    val id: String,
    val provider_id: String,
    val cache_namespace: String,
    val display_name: String,
    val base_url: String,
    val username: String,
    val token: String,
    val salt: String,
    val insecure_skip_tls_verification: Long,
    val custom_certificate_path: String?,
    val client_certificate_keystore_path: String?,
    val client_certificate_keystore_password: String?,
    val created_at_epoch_millis: Long,
    val last_connected_at_epoch_millis: Long?,
    val native_token: String?,
    val secondary_urls_json: String?,
    val custom_headers_json: String?,
    val server_connection_key: String?,
    val library_scope_key: String?,
    val selected_music_folder_ids_json: String?,
    val password: String?,
    val authentication_mode: String,
    val aurral_companion: String?,
    val identityVersion: Long = 0,
) {
    fun restore(queries: NaviampStorageQueries) {
        val previous = queries.selectMediaSourceById(id).executeAsOneOrNull()
        queries.upsertMediaSource(
            id = id,
            provider_id = provider_id,
            cache_namespace = cache_namespace,
            server_connection_key = server_connection_key,
            library_scope_key = library_scope_key,
            display_name = display_name,
            base_url = base_url,
            username = username,
            password = password,
            token = token,
            salt = salt,
            authentication_mode = authentication_mode,
            native_token = native_token,
            insecure_skip_tls_verification = insecure_skip_tls_verification,
            custom_certificate_path = custom_certificate_path,
            client_certificate_keystore_path = client_certificate_keystore_path,
            client_certificate_keystore_password = client_certificate_keystore_password,
            secondary_urls_json = secondary_urls_json,
            custom_headers_json = custom_headers_json,
            selected_music_folder_ids_json = selected_music_folder_ids_json,
            created_at_epoch_millis = created_at_epoch_millis,
            last_connected_at_epoch_millis = last_connected_at_epoch_millis,
            last_sync_started_at_epoch_millis = previous?.last_sync_started_at_epoch_millis,
            last_sync_completed_at_epoch_millis = previous?.last_sync_completed_at_epoch_millis,
            last_library_scan_signature = previous?.last_library_scan_signature,
            last_library_scan_checked_at_epoch_millis = previous?.last_library_scan_checked_at_epoch_millis,
        )
        queries.updateMediaSource(
            provider_id = provider_id,
            cache_namespace = cache_namespace,
            server_connection_key = server_connection_key,
            library_scope_key = library_scope_key,
            display_name = display_name,
            base_url = base_url,
            username = username,
            password = password,
            token = token,
            salt = salt,
            authentication_mode = authentication_mode,
            native_token = native_token,
            insecure_skip_tls_verification = insecure_skip_tls_verification,
            custom_certificate_path = custom_certificate_path,
            client_certificate_keystore_path = client_certificate_keystore_path,
            client_certificate_keystore_password = client_certificate_keystore_password,
            secondary_urls_json = secondary_urls_json,
            custom_headers_json = custom_headers_json,
            selected_music_folder_ids_json = selected_music_folder_ids_json,
            last_connected_at_epoch_millis = last_connected_at_epoch_millis,
            last_sync_started_at_epoch_millis = previous?.last_sync_started_at_epoch_millis,
            last_sync_completed_at_epoch_millis = previous?.last_sync_completed_at_epoch_millis,
            last_library_scan_signature = previous?.last_library_scan_signature,
            last_library_scan_checked_at_epoch_millis = previous?.last_library_scan_checked_at_epoch_millis,
            id = id,
        )
        queries.updateAurralCompanion(aurral_companion, id, server_connection_key.orEmpty())
        if (previous?.provider_identity_version != identityVersion) queries.markProviderIdentityVersion(identityVersion, id)
    }
}

internal fun Media_source.recoveryConnection() = StorageRecoveryConnection(
    id = id,
    provider_id = provider_id,
    cache_namespace = cache_namespace,
    display_name = display_name,
    base_url = base_url,
    username = username,
    token = token,
    salt = salt,
    insecure_skip_tls_verification = insecure_skip_tls_verification,
    custom_certificate_path = custom_certificate_path,
    client_certificate_keystore_path = client_certificate_keystore_path,
    client_certificate_keystore_password = client_certificate_keystore_password,
    created_at_epoch_millis = created_at_epoch_millis,
    last_connected_at_epoch_millis = last_connected_at_epoch_millis,
    native_token = native_token,
    secondary_urls_json = secondary_urls_json,
    custom_headers_json = custom_headers_json,
    server_connection_key = server_connection_key,
    library_scope_key = library_scope_key,
    selected_music_folder_ids_json = selected_music_folder_ids_json,
    password = password,
    authentication_mode = authentication_mode,
    aurral_companion = aurral_companion,
    identityVersion = provider_identity_version,
)
