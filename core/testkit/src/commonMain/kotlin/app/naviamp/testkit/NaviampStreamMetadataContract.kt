/** Shared contract; hosts supply only real native BASS and a temporary fixture file. */
fun verifyNaviampStreamTagReading(backend: BassAudioBackend, path: String) {
    val stream = backend.createFileDecodeStream(path).getOrThrow()
    try {
        val metadata = PlaybackStreamMetadata.fromProperties(backend.streamMetadata(stream))
        check(metadata.title == "Shared metadata title")
        val rows = InternetRadioStation("fixture", "Fixture", "https://fixture.test/live")
            .streamDetails(metadata).flatMap { it.rows }
        check(rows.any { it.label == NaviampStreamDetailLabel.Artist && it.value == "Shared metadata artist" })
        check(rows.any { it.label == NaviampStreamDetailLabel.Album && it.value == "Shared metadata album" })
        check(rows.any { it.metadataKey.equals("DJ", true) && it.value == "Shared presenter" })
    } finally { backend.freeStream(stream).getOrThrow() }
}

